#!/usr/bin/env python3
"""Aggregate raw results into markdown tables (median, min, max over runs).

usage: summarize.py [results_dir]   -> writes <results_dir>/summary.md

Every number printed here is read from a file under results/; each table row
names the files it came from. Nothing is estimated.
"""
import csv, glob, json, os, re, statistics, sys
from collections import defaultdict

R = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', 'results'))
out = []


def rel(p):
    return os.path.relpath(p, os.path.dirname(R))


def k6(path):
    with open(path) as f:
        return json.load(f)


def mv(d, metric, key='count'):
    m = d['metrics'].get(metric)
    if not m:
        return None
    return m['values'].get(key)


def runs(scn):
    return sorted(glob.glob(os.path.join(R, scn, 'run*')), key=lambda p: int(re.sub(r'\D', '', os.path.basename(p)) or 0))


def agg(vals):
    vals = [v for v in vals if v is not None]
    if not vals:
        return 'n/a'
    f = lambda x: f'{x:,.0f}' if abs(x) >= 100 or float(x).is_integer() else f'{x:,.2f}' if abs(x) < 10 else f'{x:,.1f}'
    if len(vals) == 1:
        return f(vals[0])
    return f'{f(statistics.median(vals))} ({f(min(vals))}–{f(max(vals))})'


def psql_col(text, col, nth=0):
    """Value of column `col` in the nth psql table that has it (first data row)."""
    lines = text.splitlines()
    hits = 0
    for i, line in enumerate(lines):
        cells = [c.strip() for c in line.split('|')]
        if col in cells and i + 2 < len(lines) and set(lines[i + 1].strip()) <= set('-+'):
            if hits == nth:
                row = [c.strip() for c in lines[i + 2].split('|')]
                return row[cells.index(col)] if len(row) == len(cells) else None
            hits += 1
    return None


def num(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def table(header, rows):
    out.append('| ' + ' | '.join(header) + ' |')
    out.append('|' + '---|' * len(header))
    for r in rows:
        out.append('| ' + ' | '.join(str(c) for c in r) + ' |')
    out.append('')


def status_cols(d):
    s = lambda c: mv(d, f'status_{c}') or 0
    five = sum(s(c) for c in (500, 502, 503, 504))
    return s(200) + s(201), s(409), s(429), five, s('0_no_response'), mv(d, 'status_other') or 0


def cpu_stats(path):
    per = defaultdict(list)
    if not os.path.exists(path):
        return {}
    with open(path) as f:
        for row in csv.reader(f):
            if len(row) >= 3:
                try:
                    per[row[1]].append(float(row[2].rstrip('%')))
                except ValueError:
                    pass
    return {k: (statistics.median(v), max(v)) for k, v in per.items() if v}


out.append('# Aggregated results (generated by tools/summarize.py)\n')
out.append('Format: **median (min–max)** over runs. Latency in ms. All numbers: local, single machine.\n')

# ── G1 ──
rs = runs('g1')
if rs:
    ds = [k6(f'{r}/k6.json') for r in rs]
    out.append(f'## G1 merchant creation ({len(rs)} runs)\n')
    table(['metric', 'value', 'source'], [
        ['merchants created (201)', agg([mv(d, 'status_201') for d in ds]), 'results/g1/run*/k6.json'],
        ['POST /merchants p50', agg([mv(d, 'http_req_duration', 'med') for d in ds]), 'results/g1/run*/k6.json'],
        ['POST /merchants p95', agg([mv(d, 'http_req_duration', 'p(95)') for d in ds]), 'results/g1/run*/k6.json'],
        ['POST /merchants max', agg([mv(d, 'http_req_duration', 'max') for d in ds]), 'results/g1/run*/k6.json'],
    ])

# ── G2 ──
rs = runs('g2')
if rs:
    ds = [k6(f'{r}/k6.json') for r in rs]
    inv = [open(f'{r}/invariants.txt').read() for r in rs]
    out.append(f'## G2 idempotency storm ({len(rs)} runs)\n')
    rows = []
    for name, metric, key in [
        ('requests total', 'http_reqs', 'count'),
        ('requests/s (whole test)', 'http_reqs', 'rate'),
        ('identical-request p50', 'http_req_duration{kind:identical}', 'med'),
        ('identical-request p95', 'http_req_duration{kind:identical}', 'p(95)'),
        ('identical-request p99', 'http_req_duration{kind:identical}', 'p(99)'),
        ('different-body p50', 'http_req_duration{kind:diffbody}', 'med'),
        ('different-body p99', 'http_req_duration{kind:diffbody}', 'p(99)'),
        ('status 201', 'status_201', 'count'),
        ('status 409', 'status_409', 'count'),
        ('status 429', 'status_429', 'count'),
        ('status 500', 'status_500', 'count'),
        ('no response / timeout', 'status_0_no_response', 'count'),
        ('keys: all C responses 201 and byte-identical', 'g2_keys_all_201_identical_body', 'count'),
        ('keys: ≥1 of the C responses was 409', 'g2_keys_with_409', 'count'),
        ('keys: some response neither 201 nor 409', 'g2_keys_with_non_201_non_409', 'count'),
        ('keys: 201s carried different intent ids (must be 0)', 'g2_keys_with_different_intent_ids', 'count'),
        ('409s with code idempotency_key_in_use (retryable)', 'g2_409_code_idempotency_key_in_use', 'count'),
        ('409s with code idempotency_conflict', 'g2_409_code_idempotency_conflict', 'count'),
        ('diff body → 409 idempotency_conflict (expected)', 'g2_diffbody_409_idempotency_conflict', 'count'),
        ('diff body → 201 replay of ORIGINAL intent', 'g2_diffbody_201_replayed_original', 'count'),
        ('diff body → 201 NEW intent (must be 0)', 'g2_diffbody_201_new_intent', 'count'),
        ('diff body → other status', 'g2_diffbody_other_status', 'count'),
    ]:
        rows.append([name, agg([mv(d, metric, key) for d in ds]), 'results/g2/run*/k6.json'])
    for name, col in [('SQL: intents for G2 keys', 'g2_intents'), ('SQL: duplicate (merchant,key) groups', 'duplicate_groups'),
                      ('SQL: intents created from the different body', 'intents_with_probe_amount')]:
        rows.append([name, agg([num(psql_col(t, col)) for t in inv]), 'results/g2/run*/invariants.txt'])
    mock = []
    for r in rs:
        m = re.search(r'op="create_charge",provider="stripe"} (\d+)', open(f'{r}/metrics.txt').read())
        mock.append(float(m.group(1)) if m else None)
    rows.append(['mock provider CreateCharge calls (incl. warm-up)', agg(mock), 'results/g2/run*/metrics.txt'])
    table(['metric', 'value', 'source'], rows)

# ── G3 ──
g3 = defaultdict(list)
for p in glob.glob(os.path.join(R, 'g3', 'run*', 'rate_*')):
    g3[int(p.rsplit('_', 1)[1])].append(p)
if g3:
    out.append(f'## G3 throughput curve (POST /payments, distinct keys, 60 s per rate)\n')
    rows = []
    for rate in sorted(g3):
        ps = sorted(g3[rate])
        ds = [k6(f'{p}/k6.json') for p in ps]
        thr, err, cpu_app, cpu_pg = [], [], [], []
        for d, p in zip(ds, ps):
            ok, c409, c429, five, none, other = status_cols(d)
            total = ok + c409 + c429 + five + none + other
            dur = d['state']['testRunDurationMs'] / 1000
            thr.append(ok / dur)
            err.append(100 * (total - ok) / total if total else None)
            c = cpu_stats(f'{p}/docker_stats.csv')
            cpu_app.append(c.get('lt_gateway_app', (None, None))[0])
            cpu_pg.append(c.get('lt_gateway_postgres', (None, None))[0])
        rows.append([rate, len(ps), agg(thr),
                     agg([mv(d, 'http_req_duration', 'med') for d in ds]),
                     agg([mv(d, 'http_req_duration', 'p(95)') for d in ds]),
                     agg([mv(d, 'http_req_duration', 'p(99)') for d in ds]),
                     agg(err),
                     agg([mv(d, 'dropped_iterations') or 0 for d in ds]),
                     agg(cpu_app), agg(cpu_pg),
                     f'results/g3/run*/rate_{rate}/'])
    table(['target req/s', 'runs', '201/s achieved', 'p50', 'p95', 'p99', 'error %', 'dropped iterations',
           'app CPU % (median sample)', 'postgres CPU % (median sample)', 'source'], rows)
    out.append('error % = responses that were not 201 (incl. no response) / responses. 201/s = 201 count / k6 test duration '
               '(includes up to 40 s graceful stop at saturated rates). Dropped iterations = arrivals k6 could not start '
               '(no free VU, maxVUs=600). CPU % from `docker stats` (100 % = one core).\n')

# ── G4 / G8 ──
for scn, title in [('g4', 'G4 webhook → ledger (one instance)'), ('g8', 'G8 webhook → ledger (two instances)')]:
    rs = runs(scn)
    if not rs:
        continue
    ds = [k6(f'{r}/k6.json') for r in rs]
    plans = [json.load(open(f'{r}/plan.json')) for r in rs]
    inv = [open(f'{r}/invariants.txt').read() for r in rs]
    wall = []
    for r in rs:
        m = re.search(r'wall_end_of_delivery_to_zero_pending_s=([\d.]+)', open(f'{r}/drain_wallclock.txt').read())
        wall.append(float(m.group(1)) if m else None)
    out.append(f'## {title} ({len(rs)} runs)\n')
    rows = [
        ['intents (seeded)', agg([p['intents'] for p in plans]), f'results/{scn}/run*/plan.json'],
        ['unique event ids sent', agg([p['unique_events'] for p in plans]), f'results/{scn}/run*/plan.json'],
        ['webhook deliveries sent (1–5 copies per event)', agg([mv(d, 'g4_deliveries_sent') for d in ds]), f'results/{scn}/run*/k6.json'],
        ['ingest responses 200', agg([mv(d, 'status_200') for d in ds]), f'results/{scn}/run*/k6.json'],
        ['ingest responses not 200', agg([mv(d, 'g4_non_200_responses') for d in ds]), f'results/{scn}/run*/k6.json'],
        ['ingest req/s (whole delivery phase)', agg([mv(d, 'http_reqs', 'rate') for d in ds]), f'results/{scn}/run*/k6.json'],
        ['ingest p50', agg([mv(d, 'http_req_duration', 'med') for d in ds]), f'results/{scn}/run*/k6.json'],
        ['ingest p95', agg([mv(d, 'http_req_duration', 'p(95)') for d in ds]), f'results/{scn}/run*/k6.json'],
        ['ingest p99', agg([mv(d, 'http_req_duration', 'p(99)') for d in ds]), f'results/{scn}/run*/k6.json'],
        ['wall: end of delivery → 0 pending (s)', agg(wall), f'results/{scn}/run*/drain_wallclock.txt'],
        ['DB: last ingest → last processed (s)', agg([num(psql_col(t, 'drain_after_last_ingest_s')) for t in inv]), f'results/{scn}/run*/invariants.txt'],
        ['DB: processing span (s)', agg([num(psql_col(t, 'processing_span_s')) for t in inv]), f'results/{scn}/run*/invariants.txt'],
        ['DB: rows processed per second', agg([num(psql_col(t, 'processed_per_s')) for t in inv]), f'results/{scn}/run*/invariants.txt'],
    ]
    if scn == 'g8':
        for app in ('app1', 'app2'):
            vals = []
            for r in rs:
                txt = open(f'{r}/metrics_{app}.txt').read() if os.path.exists(f'{r}/metrics_{app}.txt') else ''
                m = re.search(r'gateway_webhooks_processed_total\{outcome="processed",provider="stripe"} (\d+)', txt)
                vals.append(float(m.group(1)) if m else 0.0)
            rows.append([f'webhooks processed by {app} (Prometheus counter)', agg(vals), f'results/{scn}/run*/metrics_{app}.txt'])
        rows.append(['deliveries sent to app1 / app2', f"{agg([mv(d, 'g4_deliveries_to_app1') for d in ds])} / {agg([mv(d, 'g4_deliveries_to_app2') for d in ds])}", f'results/{scn}/run*/k6.json'])
    inv_rows = [
        ('I1 ledger sum (must be 0)', 'ledger_sum', 0),
        ('I2 unbalanced intents (must be 0)', 'unbalanced_intents', 0),
        ('I3 succeeded without ledger (must be 0)', 'succeeded_without_ledger', 0),
        ('I3 succeeded with ≠3 legs (must be 0)', 'succeeded_with_wrong_leg_count', 0),
        ('I4 non-succeeded with ledger (must be 0)', 'non_succeeded_with_ledger', 0),
        ('I5 seeded intents succeeded', 'seeded_succeeded', 0),
        ('I6 webhook rows', 'webhook_rows', 0),
        ('I6 distinct (provider, event id)', 'distinct_events', 0),
        ('I7 provider-leg amount mismatches (must be 0)', 'provider_leg_mismatch', 0),
    ]
    for name, col, nth in inv_rows:
        rows.append([name, agg([num(psql_col(t, col, nth)) for t in inv]), f'results/{scn}/run*/invariants.txt'])
    oks = [all(x == 't' for x in re.findall(r'\|\s*([tf])\s*$', t, re.M)) for t in inv]
    rows.append(['all `ok` columns true in every run', 'yes' if all(oks) else f'NO ({oks})', f'results/{scn}/run*/invariants.txt'])
    table(['metric', 'value', 'source'], rows)

# ── G5 ──
rs = runs('g5')
if rs:
    ds = [k6(f'{r}/k6.json') for r in rs]
    inv = [open(f'{r}/invariants.txt').read() for r in rs]
    out.append(f'## G5 concurrent refunds ({len(rs)} runs) — payment amount 10000 each\n')
    rows = []
    for sub, desc in [('a', '20 parallel, distinct keys, amounts 1000..1019 (sum 20190)'),
                      ('b', '20 parallel, distinct keys, 3000 each (sum 60000)'),
                      ('c', '10 parallel, same key, 2000'),
                      ('d', 'sequential 6000 then 6001')]:
        rows.append([f'{sub}: {desc}',
                     agg([mv(d, f'g5{sub}_status_201') for d in ds]),
                     agg([mv(d, f'g5{sub}_status_409') for d in ds]),
                     agg([mv(d, f'g5{sub}_status_500') for d in ds]),
                     agg([mv(d, f'g5{sub}_status_other') for d in ds]),
                     f'results/g5/run*/k6.json'])
    table(['sub-test', '201', '409', '500', 'other', 'source'], rows)
    succ, calls = [], []
    for r in rs:
        txt = open(f'{r}/invariants.txt').read()
        succ.append(float(len(re.findall(r'\|\s*succeeded\s*\|\s*$', txt, re.M))))
        m = re.search(r'op="refund",provider="stripe"} (\d+)', open(f'{r}/metrics.txt').read())
        calls.append(float(m.group(1)) if m else 0.0)
    table(['invariant / count', 'value', 'source'], [
        ['payments over-refunded (must be 0)', agg([num(psql_col(t, 'over_refunded_payments')) for t in inv]), 'results/g5/run*/invariants.txt'],
        ['ledger sum overall (must be 0)', agg([num(psql_col(t, 'ledger_sum')) for t in inv]), 'results/g5/run*/invariants.txt'],
        ['payments with unbalanced ledger (must be 0)', agg([num(psql_col(t, 'unbalanced_payments')) for t in inv]), 'results/g5/run*/invariants.txt'],
        ['refund rows with status succeeded', agg(succ), 'results/g5/run*/invariants.txt'],
        ['mock provider Refund calls', agg(calls), 'results/g5/run*/metrics.txt'],
    ])

# ── G6 ──
rs = runs('g6')
if rs:
    out.append(f'## G6 outbound webhooks ({len(rs)} runs)\n')
    rows = []
    for r in rs:
        st = json.load(open(f'{r}/receiver_stats.json'))
        o = open(f'{r}/outbound.txt').read()
        w = open(f'{r}/flaky_drain_wallclock.txt').read().strip()
        rows.append([os.path.basename(r), st['requests_total'], st['signature_valid'], st['signature_invalid'],
                     st['keys_whose_body_changed_between_attempts'], st['intents_seen_under_more_than_one_key'],
                     json.dumps(st['attempts_per_key_histogram'], sort_keys=True),
                     psql_col(o, 'first_enqueue_to_last_delivered_s'), psql_col(o, 'median_enqueue_to_delivered_s'),
                     re.sub(r'\D*=(\d+).*', r'\1', w), f'results/g6/{os.path.basename(r)}/'])
    table(['run', 'receiver requests', 'sig valid', 'sig invalid', 'keys w/ changed body', 'events under >1 key',
           'attempts per key {attempts: keys} (flaky+dead)', 'flaky: first enqueue→last delivered (s, DB)',
           'flaky: median enqueue→delivered (s, DB)', 'flaky: wall drain (s)', 'source'], rows)
    out.append('Backoff tables per run: `results/g6/run*/backoff.txt`. Status/attempt distribution: `results/g6/run*/outbound.txt`.\n')

# ── G9 ──
rs = runs('g9')
if rs:
    dm = [k6(f'{r}/k6_merchant.json') for r in rs]
    di = [k6(f'{r}/k6_ip.json') for r in rs]
    out.append(f'## G9 rate limits at defaults ({len(rs)} runs)\n')
    rows = [[n, agg([mv(d, m) for d in ds]), f'results/g9/run*/{f}'] for n, m, ds, f in [
        ('A per-merchant (limit 600/min), 20 req/s for 50 s: 201', 'g9a_201', dm, 'k6_merchant.json'),
        ('A per-merchant: 429 with code rate_limit_exceeded', 'g9a_429_rate_limit_exceeded', dm, 'k6_merchant.json'),
        ('A per-merchant: 429 other body', 'g9a_429_other', dm, 'k6_merchant.json'),
        ('A per-merchant: other status', 'g9a_other', dm, 'k6_merchant.json'),
        ('B one client IP (limit 200/min), 300 × GET /health: 200', 'g9b_200', di, 'k6_ip.json'),
        ('B one client IP: 429', 'g9b_429', di, 'k6_ip.json'),
        ('C rotating X-Real-IP header, 300 × GET /health: 200', 'g9c_200', di, 'k6_ip.json'),
        ('C rotating X-Real-IP header: 429', 'g9c_429', di, 'k6_ip.json'),
    ]]
    rows.append(['A latency of 201 responses p50', agg([mv(d, 'http_req_duration{scenario:a_merchant,status:201}', 'med') for d in dm]), 'results/g9/run*/k6_merchant.json'])
    rows.append(['A latency of 429 responses p50', agg([mv(d, 'http_req_duration{scenario:a_merchant,status:429}', 'med') for d in dm]), 'results/g9/run*/k6_merchant.json'])
    table(['metric', 'value', 'source'], rows)

# ── G10 ──
p10 = os.path.join(R, 'g10', 'run1', 'after.txt')
if os.path.exists(p10):
    t = open(p10).read()
    out.append('## G10 reconciler (1 run)\n')
    m = re.search(r'reconciler_corrected_log_lines=(\d+)', t)
    table(['metric', 'value', 'source'], [
        ['seeded intents succeeded after reconciliation', psql_col(t, 'seeded_succeeded'), 'results/g10/run1/after.txt'],
        ['succeeded intents without ledger', psql_col(t, 'succeeded_without_ledger'), 'results/g10/run1/after.txt'],
        ['ledger sum', psql_col(t, 'ledger_sum'), 'results/g10/run1/after.txt'],
        ['outbound deliveries enqueued', psql_col(t, 'outbound_deliveries_enqueued'), 'results/g10/run1/after.txt'],
        ['"reconciler corrected" log lines', m.group(1) if m else 'n/a', 'results/g10/run1/after.txt'],
        ['wall clock', open(os.path.join(R, 'g10', 'run1', 'wallclock.txt')).read().strip(), 'results/g10/run1/wallclock.txt'],
    ])

with open(os.path.join(R, 'summary.md'), 'w') as f:
    f.write('\n'.join(out) + '\n')
print('\n'.join(out))
